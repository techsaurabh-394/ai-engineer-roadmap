#!/usr/bin/env python3
"""Generate every animated explainer.

Writes assets/anim/*.svg and docs/animations.md from the specs in
scripts/anim_specs_*.py. Standard library only.

    python scripts/gen_animations.py
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import anim_core as core  # noqa: E402
import anim_specs_a, anim_specs_b, anim_specs_c  # noqa: E402,F401  (registers animations)

OUT = core.ROOT / "assets" / "anim"
PHASES = {"01": "Phase 1: RAG foundations", "02": "Phase 2: Advanced RAG", "03": "Phase 3: LLM concepts",
          "04": "Phase 4: Agentic AI", "05": "Phase 5: Frameworks", "06": "Phase 6: MCP", "07": "Phase 7: Production AI"}


def phase_of(a):
    return a["topics"][0].split("-")[0] if a["topics"] else "00"


def build():
    """Return a list of dicts: spec plus svg, dur, marks, steps."""
    errs = [e for a in core.REGISTRY.values() for e in core.lint(a)]
    if errs:
        raise SystemExit("text does not fit:\n  " + "\n  ".join(errs))
    out = []
    for name in sorted(core.REGISTRY):
        a = core.REGISTRY[name]
        svg, dur, marks, steps = core.render(a)
        out.append(dict(a, svg=svg, dur=dur, marks=marks, steps=steps, phase=phase_of(a)))
    return out


def title_of_topic(rel):
    return (core.ROOT / rel).read_text(encoding="utf-8").split("\n")[0].lstrip("# ").strip()


def gallery(anims):
    md = ["# Animated explainers\n",
          f"{len(anims)} short animations that show the hard ideas moving, one step at a time. Each one loops: watch the "
          "highlighted box and read the caption underneath. Every animation is also embedded in its topic page under **Watch it**.\n",
          "Want to go at your own pace? Open the [interactive viewer](https://techsaurabh-394.github.io/ai-engineer-roadmap/) "
          "and use Previous, Play and Next, or the arrow keys.\n",
          "This page is generated by `python scripts/gen_animations.py`; do not edit it by hand.\n"]
    for ph in sorted(PHASES):
        group = [a for a in anims if a["phase"] == ph]
        if not group:
            continue
        md.append(f"\n## {PHASES[ph]}\n")
        for a in sorted(group, key=lambda x: x["topics"][0]):
            links = ", ".join(f"[{title_of_topic(t)}](../{t})" for t in a["topics"])
            md.append(f"### {a['title']}\n\n*Lesson: {links}*\n\n![{a['title']}: {a['subtitle']}](../assets/anim/{a['name']}.svg)\n")
    return "\n".join(md)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    anims = build()
    keep = {a["name"] + ".svg" for a in anims}
    for old in OUT.glob("*.svg"):
        if old.name not in keep:
            old.unlink()
    for a in anims:
        (OUT / f"{a['name']}.svg").write_text(a["svg"], encoding="utf-8")
    (core.ROOT / "docs" / "animations.md").write_text(gallery(anims), encoding="utf-8")
    covered = {t for a in anims for t in a["topics"]}
    all_topics = {p.relative_to(core.ROOT).as_posix() for p in core.ROOT.glob("0[1-7]*/topics/*.md")}
    print(f"wrote {len(anims)} svgs; {len(covered)} of {len(all_topics)} topic pages covered")
    missing = sorted(all_topics - covered)
    if missing:
        print("not covered:", *missing, sep="\n  ")


if __name__ == "__main__":
    main()
